/// Spacing and sizing constants for TaskFlow mobile app
/// Following Material Design 3 spacing scale (8dp grid)
class AppSpacing {
  AppSpacing._();

  // Spacing scale (based on 8dp grid)
  static const double none = 0.0;
  static const double xs = 4.0; // Extra small
  static const double sm = 8.0; // Small
  static const double md = 16.0; // Medium (base unit)
  static const double lg = 24.0; // Large
  static const double xl = 32.0; // Extra large
  static const double xxl = 40.0; // 2x Extra large
  static const double xxxl = 48.0; // 3x Extra large

  // Layout spacing
  static const double screenPadding = md; // Default screen padding
  static const double cardPadding = md; // Card internal padding
  static const double listItemPadding = md; // List item padding
  static const double sectionSpacing = lg; // Spacing between sections
  static const double bottomNavHeight = 80.0; // Bottom navigation bar height

  // Icon sizes
  static const double iconXs = 16.0;
  static const double iconSm = 20.0;
  static const double iconMd = 24.0;
  static const double iconLg = 32.0;
  static const double iconXl = 48.0;
  static const double iconXxl = 64.0;

  // Avatar sizes
  static const double avatarSm = 32.0;
  static const double avatarMd = 48.0;
  static const double avatarLg = 64.0;
  static const double avatarXl = 96.0;

  // Button heights
  static const double buttonHeightSm = 36.0;
  static const double buttonHeightMd = 48.0;
  static const double buttonHeightLg = 56.0;

  // Border radius
  static const double radiusXs = 4.0;
  static const double radiusSm = 8.0;
  static const double radiusMd = 12.0;
  static const double radiusLg = 16.0;
  static const double radiusXl = 24.0;
  static const double radiusFull = 999.0; // Fully rounded

  // Elevation (Material Design 3 shadow levels)
  static const double elevationNone = 0.0;
  static const double elevationLow = 1.0;
  static const double elevationMedium = 3.0;
  static const double elevationHigh = 6.0;
  static const double elevationHighest = 12.0;

  // Input field heights
  static const double inputHeightSm = 40.0;
  static const double inputHeightMd = 48.0;
  static const double inputHeightLg = 56.0;

  // Divider thickness
  static const double dividerThin = 0.5;
  static const double dividerThick = 1.0;

  // Progress indicator sizes
  static const double progressIndicatorSm = 16.0;
  static const double progressIndicatorMd = 24.0;
  static const double progressIndicatorLg = 48.0;
}
